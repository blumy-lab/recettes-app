export function searchIngredients(query: string): string[] {
  if (query.length < 2) return []
  const q = query.toLowerCase().trim()
  const exact: string[] = []
  const starts: string[] = []
  const contains: string[] = []
  for (const ing of INGREDIENTS) {
    const l = ing.toLowerCase()
    if (l === q) exact.push(ing)
    else if (l.startsWith(q)) starts.push(ing)
    else if (l.includes(q)) contains.push(ing)
  }
  return [...exact, ...starts, ...contains].slice(0, 7)
}
